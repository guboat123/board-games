const recent = {};
const RECENT_KEEP = 8;

/* ---------- เสียงประจำตัว ----------
   ⚠️ เจ้าของสั่ง "personality ไม่ต้องเหมือนกัน" (2026-09-04)
   ถ้าทุกตัวสุ่มจากกองเดียวกันเท่า ๆ กัน สามสิบตัวจะพูดเหมือนกันหมดในระยะยาว
   ต่อให้ความถี่ต่างกัน คำที่ออกมาก็ชุดเดียวกัน = จำไม่ได้ว่าใครเป็นใคร

   แก้ด้วยการให้แต่ละชื่อมีเลขประจำตัวคงที่ (คิดจากชื่อ ไม่ใช่สุ่มใหม่ทุกครั้ง)
   แล้วให้มัน "ชอบ" คำครึ่งหนึ่งของกอง — Rocco จึงพูดแบบ Rocco ทุกวง ข้ามการรีสตาร์ตด้วย
   ไม่ได้ล็อกตายตัว อีกครึ่งยังออกได้ แค่ไม่บ่อย จึงยังไม่ซ้ำซากอยู่ดี */
const voices = {};
function voiceOf(name) {
  if (voices[name] !== undefined) return voices[name];
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0;
  voices[name] = (h % 1000) / 1000;
  return voices[name];
}

function pick(list, name) {
  if (!list || !list.length) return "";
  if (list.length === 1) return list[0];
  const seen = recent[name] || (recent[name] = []);
  let from = list.filter(function (s) { return seen.indexOf(s) === -1; });
  if (!from.length) from = list;
  /* คำที่ "ตรงเสียง" ของตัวนี้ ถูกหยิบบ่อยกว่า — สองในสามของครั้ง */
  if (from.length > 2 && Math.random() < 0.67) {
    const v = voiceOf(name);
    const mine = from.filter(function (s, i) {
      return Math.abs(((i / from.length) - v + 1) % 1) < 0.5;
    });
    if (mine.length) from = mine;
  }
  const line = from[Math.floor(Math.random() * from.length)];
  seen.push(line);
  while (seen.length > RECENT_KEEP) seen.shift();
  return line;
}

/* ---------- พูดตอนอารมณ์ถึง ----------
   ⚠️ เจ้าของทักถูก: ถ้าใช้ความน่าจะเป็นคงที่ต่อจังหวะ มันจะ "fix" คือทอยลูกเต๋าเฉย ๆ
   บอทที่เพิ่งเก็บกองยักษ์ กับบอทที่นั่งเงียบมาสิบมือ พูดบ่อยเท่ากัน ซึ่งไม่ใช่คน
   คนพูดตอน "อารมณ์ถึง" — เพิ่งได้เยอะแล้วคัน · เพิ่งเสียหนักแล้วอัด · เงินร่อยหรอแล้วเงียบ

   มิเตอร์สองตัวที่เจ้าของเสนอ มีอยู่ในเกมแล้วครึ่งหนึ่ง แค่ไม่เคยต่อเข้าปาก:
     cocky = mood.confidence  ขึ้นเมื่อเก็บกองใหญ่ จางลง 15% ทุกมือ (มีอยู่แล้ว ใช้กับการเล่นด้วย)
     tilt  = mood.tilt        ขึ้นเมื่อเสียหนัก จางลง 18% ทุกมือ (มีอยู่แล้ว)
     scare = คำนวณจากเงินที่เหลือจริง (ดู bots.mjs) — ของใหม่สำหรับปากอย่างเดียว
   ⚠️ ห้ามสร้างมิเตอร์ใหม่ที่ซ้ำกับของเดิม ไม่งั้นจะมีสองชุดที่ค่อย ๆ ไม่ตรงกัน
   แล้วบอทจะ "พูดเหมือนกำลังกลัว" ทั้งที่ "เล่นเหมือนกำลังกล้า" */
const EVENT_CHANCE = {
  folded:   0.02,   /* หมอบทิ้งเฉย ๆ แทบไม่มีใครพูด */
  raised:   0.05,   /* ยั่วตอนไล่ มีจริง แต่ไม่ใช่ทุกครั้งที่ไล่ */
  wonQuiet: 0.08,   /* เก็บกองเล็กแบบไม่มีใครสู้ */
  won:      0.17,   /* ชนะตอนเปิดไพ่ = เงินขยับจริง คนพูดกันตรงนี้ */
  lost:     0.17,
  niceHand: 0.17,
  bust:     0.45,   /* หมดตัวแล้วเงียบ ๆ ไม่ค่อยมี */
  leaving:  1        /* คำลา พูดทุกครั้ง */
};

/* อารมณ์ตอนนี้แรงแค่ไหน 0 = เรียบ ๆ ไม่มีอะไรจะพูด · 1 = คันปากเต็มที่ */
function heatOf(c) {
  const m = c.mood || {};
  return Math.min(1, Math.max(
    m.confidence || 0,
    m.tilt || 0,
    (c.scare || 0) * 0.8,
    (m.boredom || 0) * 0.7
  ));
}

/* เสียหนักจนรวน — ใช้ทั้งตอนคิดความถี่และตอนเลือกโทน จะได้ตรงกันเสมอ */
function isTilted(c) { return ((c.mood || {}).tilt || 0) > 0.45; }

/* โทนเสียงตอนนี้ — ตัวเดียวกับที่ใช้เลือกว่าจะพูดชุดไหน
   ⚠️ กลัวมาก่อนกล้า คนที่เพิ่งได้กองใหญ่แต่กระเป๋าใกล้หมด ยังเงียบอยู่ดี
   (เงินในกระเป๋าคือสิ่งที่คนคิดถึงจริง ๆ ไม่ใช่กองที่เพิ่งได้) */
function toneOf(c) {
  const m = c.mood || {};
  if ((c.scare || 0) > 0.55) return "meek";
  /* รวนเหมือนกัน แต่ออกคนละทาง — ปากไวโวยวาย เก็บอาการก็งอนเงียบ */
  if (isTilted(c)) return ((c.trait || {}).bluffy || 1) > 1 ? "tilted" : "sulk";
  if ((m.confidence || 0) > 0.45) return "cocky";
  return "flat";
}

function chanceFor(c) {
  const t = c.trait || {};
  let p = EVENT_CHANCE[c.event];
  if (p === undefined) p = 0.05;
  if (p >= 1) return 1;

  /* ⚠️ ประตูอารมณ์ — ตัวที่ทำให้ไม่ fix
     อารมณ์เรียบ = พูดน้อยกว่าครึ่ง · อารมณ์พุ่ง = พูดได้เกือบสามเท่า
     ผลคือบอทเงียบไปทั้งช่วงที่ไม่มีอะไรเกิด แล้วมาออกรัวตอนมีเรื่อง ซึ่งคือคน */
  const heat = heatOf(c);
  p *= 0.45 + heat * 2.2;

  /* ⚠️ "เงียบก็คืออารมณ์" — ของเดิมผิดตรงนี้: ให้ทุกคนเสียแล้วพูดมากขึ้น 1.6 เท่าเหมือนกันหมด
     ซึ่งไม่จริงเลย ที่โต๊ะจริงคนเสียหนักแยกเป็นสองพวกชัดมาก
     พวกปากไว (bluffy สูง) เสียแล้วเสียงดังขึ้น · พวกเก็บอาการ (bluffy ต่ำ) เงียบสนิทไปเลย
     และความเงียบของคนหลังคือสิ่งที่คนทั้งโต๊ะสังเกตเห็น ไม่ใช่ความว่างเปล่า */
  if (isTilted(c)) {
    /* ⚠️ ไม่ใช่ "สองพวก" — ไล่ต่อเนื่องตามนิสัยของแต่ละตัว
       bluffy 0.4 (Ash) ได้ 0.12 เท่า = เงียบกว่าปกติชัดเจน
       bluffy 1.0 (กลาง)  ได้ 1.0 เท่า = ไม่เปลี่ยน
       bluffy 1.8 (Rudy)  ได้ 2.3 เท่า = เสียงดังขึ้นจริง
       สามสิบตัวจึงตกคนละจุดบนเส้นเดียวกัน ไม่มีสองตัวไหนเหมือนกันเป๊ะ */
    const b2 = t.bluffy === undefined ? 1 : t.bluffy;
    p *= Math.max(0.1, Math.pow(b2, 2.6));
  }

  /* คนที่ชอบบลัฟ = คนที่ชอบกวนด้วย */
  p *= 0.7 + (t.bluffy || 1) * 0.45;
  /* คนใจเย็นรอจังหวะ พูดน้อยกว่า */
  p *= 1.15 - (t.patience || 0.5) * 0.4;
  /* กลัวเงินหมดแล้วเงียบ ไม่ว่าจะเพิ่งได้หรือเพิ่งเสีย */
  p *= 1 - (c.scare || 0) * 0.55;
  /* กองใหญ่เรื่องใหญ่ พูดถึงมากกว่ากองเล็ก */
  if (c.potShare > 0.5) p *= 1.5;
  return Math.min(Math.max(p, 0), 0.6);
}

/* เปิดให้ฝั่งเกมถามได้ว่า "ตอนนี้ตัวนี้อารมณ์ไหน" โดยไม่ต้องให้มันพูด
   ⚠️ เจ้าของทัก: "เงียบก็คืออารมณ์" และ "อารมณ์ดี เงียบยิ้ม ๆ"
   ถ้าอารมณ์ออกได้ทางคำพูดทางเดียว ตัวที่เงียบก็จะดูเหมือนไม่มีอะไรอยู่ข้างใน
   ทั้งที่มันอาจกำลังคึกสุดหรือกำลังงอนอยู่ — หน้าจอเอาค่านี้ไปขึ้นเป็นสีหน้าแทน */
export function toneFor(ctx) { return toneOf(ctx || {}); }

/* ---------- ตัวหลัก ----------
   ctx = { name, level, trait, mood, event, target, potShare, foe, read }
   ⚠️ ไม่มีช่องไพ่ และห้ามเพิ่มเข้ามาไม่ว่ากรณีใด
   คืน "" ถ้ารอบนี้ไม่พูด ซึ่งเป็นผลลัพธ์ปกติที่สุด */
export function lineFor(ctx) {
  if (!ctx || !ctx.event) return "";
  const c = ctx;
  /* ตอนลุกจากโต๊ะพูดเสมอ — เกิดครั้งเดียวจริง ๆ และเป็นจังหวะที่ควรมีคำลา */
  const always = c.event === "leaving";
  if (!always && Math.random() > chanceFor(c)) return "";

  /* ถ้ามีเรื่องในความจำกับคนที่เกี่ยวข้องในจังหวะนี้ ให้พูดเรื่องนั้นก่อน
     เพราะมันคือประโยคที่มีความหมายที่สุด และเป็นเหตุผลที่ทำฟีเจอร์นี้ตั้งแต่แรก
     (มืออาชีพจำแม่นกว่า จึงหยิบความจำมาพูดบ่อยกว่า) */
  if (c.target && (c.event === "won" || c.event === "foldedTo" ||
                   c.event === "lost" || c.event === "niceHand")) {
    /* ⚠️ ยิ่งคึกยิ่งขุดความจำมากวนคนเจาะจง ซึ่งเป็นการกวนที่แสบกว่าพูดลอย ๆ
       (คนที่กำลังได้ จะเริ่มทวงเรื่องเก่า — คนที่กำลังกลัว ไม่มีใครทำแบบนั้น) */
    let memChance = c.level === 3 ? 0.55 : c.level === 2 ? 0.35 : 0.15;
    memChance *= 1 + (c.mood && c.mood.confidence || 0) * 0.8;
    memChance *= 1 - (c.scare || 0) * 0.7;
    if (Math.random() < memChance) {
      const hits = MEMORY_LINES.filter(function (m) { return m.when(c); });
      if (hits.length) {
        const m = hits[Math.floor(Math.random() * hits.length)];
        const line = pick(m.lines, c.name);
        if (line) return line;
      }
    }
  }

  /* ⚠️ อารมณ์ชนะเหตุการณ์ ถ้ากำลังคึกหรือกำลังรวนจริง ๆ คนพูดถึง "ตัวเอง"
     มากกว่าพูดถึงมือที่เพิ่งจบ — "โต๊ะนี้ของผมละนะ" ไม่ได้เกี่ยวกับมือไหนเลย
     ไม่ใช้กับคำลาและตอนหมดตัว สองอันนั้นมีเรื่องของตัวเองอยู่แล้ว */
  const tone = toneOf(c);
  if (tone !== "flat" && c.event !== "leaving" && c.event !== "bust" &&
      Math.random() < (tone === "sulk" ? 0.75 : tone === "meek" ? 0.5 : 0.4)) {
    const pool = TONE_LINES[tone];
    const line = pick((pool && (pool[c.level] || pool[2])) || [], c.name);
    if (line) return line;
  }

  const byEvent = LINES[c.event];
  if (!byEvent) return "";
  return pick(byEvent[c.level] || byEvent[2] || [], c.name);
}

/* เปิดให้เทสต์ตรวจได้ว่าทุกประโยคที่เป็นไปได้ ไม่มีคำที่บอกไพ่เลย */
export function _allLines() {
  const out = [];
  for (const ev in LINES) {
    for (const lv in LINES[ev]) {
      LINES[ev][lv].forEach(function (s) { if (out.indexOf(s) === -1) out.push(s); });
    }
  }
  for (const tn in TONE_LINES) {
    for (const lv in TONE_LINES[tn]) {
      TONE_LINES[tn][lv].forEach(function (s) { if (out.indexOf(s) === -1) out.push(s); });
    }
  }
  MEMORY_LINES.forEach(function (m) {
    m.lines.forEach(function (s) { if (out.indexOf(s) === -1) out.push(s); });
  });
  return out;
}

/* จำนวนประโยคต่อช่อง ใช้ในเทสต์ว่ามีมากพอที่จะไม่ซ้ำในวงเดียว */
export function _poolSizes() {
  const out = {};
  for (const ev in LINES) {
    for (const lv in LINES[ev]) out[ev + ":" + lv] = LINES[ev][lv].length;
  }
  MEMORY_LINES.forEach(function (m) { out["mem:" + m.key] = m.lines.length; });
  for (const tn in TONE_LINES) {
    for (const lv in TONE_LINES[tn]) out["tone:" + tn + ":" + lv] = TONE_LINES[tn][lv].length;
  }
  return out;
}
